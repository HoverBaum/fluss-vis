import { END_NODE_ID, START_NODE_ID } from '@/stores/nodeHelpers'
import { FlussArgument, FlussFunction } from './useExport'
import { FlussTSStateJSONEnd, FlussTSStateJSONStart } from '@/lib/constants'

// String.raw helper for clean template sections
const ts = String.raw

// Input for generating a complete, typed runner file for the current flow
type FlussTemplateParams = {
  customTypes: string
  flussFunctions: FlussFunction[]
  flussInputs: FlussArgument[]
  entireStateJSON: string
}

// ---------- Small helpers to render sections ----------

const renderBanner = () => ts`/**
 * Auto-generated by flussTemplate.
 * Sections below are assembled from the current flow graph to produce a typed runner.
 */`

const renderCustomTypes = (customTypes: string) => ts`
// Custom type definitions from the editor
${customTypes}`

const renderFlussInputs = (inputs: FlussArgument[]) => ts`
export type FlussInputs = {
  ${inputs.map((arg) => `${arg.identifier}: ${arg.type}`).join(';\n  ')}
}`

const renderStepFunctionTypes = (flussFunctions: FlussFunction[]) =>
  flussFunctions
    .filter((fn) => fn.stepId !== END_NODE_ID)
    .map(
      (fn) => ts`
export type ${fn.functionTypeIdentifier} = (args: {
  ${fn.arguments.map((arg) => `${arg.name}: ${arg.type}`).join(';\n  ')}
}) => Promise<${fn.returnType}> | ${fn.returnType}
`
    )
    .join('\n')

const renderStepFunctionsContract = (flussFunctions: FlussFunction[]) => {
  const executableFunctions = flussFunctions.filter((fn) => fn.stepId !== END_NODE_ID)
  if (executableFunctions.length === 0) {
    return ts`
export type StepFunctions = {}`
  }
  return ts`
export type StepFunctions = {
  ${executableFunctions
    .map((fn) => `${fn.functionName}: ${fn.functionTypeIdentifier}`)
    .join(';\n  ')}
}`
}

const renderEndTypes = (flussFunctions: FlussFunction[]) => {
  const endFunction = flussFunctions.find((fn) => fn.stepId === END_NODE_ID)
  if (!endFunction) {
    return ts`
type EndInput = never
type EndOutput = never`
  }
  return ts`
type EndInput = {
  ${endFunction.arguments.map((arg) => `${arg.name}: ${arg.type}`).join(';\n  ')}
}
type EndOutput = ${endFunction.returnType}`
}

const renderInputAssignments = (fn: FlussFunction) => {
  if (fn.arguments.length === 0) return '{}'
  return ts`{
  ${fn.arguments
    .map((arg) => {
      const sourceReference =
        arg.source === START_NODE_ID
          ? `(await ${START_NODE_ID}ResultPromise)`
          : `(await ${arg.source}ResultPromise)`
      const valueReference = arg.usesEntireOutput
        ? sourceReference
        : `${sourceReference}.${arg.name}`
      return `${arg.name}: ${valueReference}`
    })
    .join(',\n  ')}
}`
}

const renderRunner = (flussFunctions: FlussFunction[]) => ts`
export async function runFluss(params: {
  inputs: FlussInputs
  stepFunctions: StepFunctions
}): Promise<EndOutput> {
  const { inputs, stepFunctions } = params

  const ${START_NODE_ID}ResultPromise: Promise<FlussInputs> =
    Promise.resolve(inputs)
${flussFunctions
  .map((fn) => {
    const inputVariable = `${fn.functionName}Input`
    const resultVariable = `${fn.functionName}ResultPromise`
    if (fn.stepId === END_NODE_ID) {
      return ts`
  const ${resultVariable}: Promise<EndOutput> = (async () => {
    const ${inputVariable}: EndInput = ${renderInputAssignments(fn)}
    return ${inputVariable}
  })()
  return await ${resultVariable}`
    }
    return ts`
  const ${resultVariable}: Promise<Awaited<ReturnType<${fn.functionTypeIdentifier}>>> = (async () => {
    const ${inputVariable}: Parameters<${fn.functionTypeIdentifier}>[0] = ${renderInputAssignments(fn)}
    return await stepFunctions.${fn.functionName}(${inputVariable})
  })()`
  })
  .join('\n')}

  throw new Error('Generated flow has no end step.')
}
`

export const flussTemplate = ({
  customTypes,
  flussFunctions,
  flussInputs,
  entireStateJSON,
}: FlussTemplateParams) => ts`
${renderBanner()}

// ===== Section: Custom Types =====
${renderCustomTypes(customTypes)}

// ===== Section: Flow Inputs =====
${renderFlussInputs(flussInputs)}

// ===== Section: Step Function Signatures (from node definitions) =====
${renderStepFunctionTypes(flussFunctions)}

// ===== Section: Runtime Contracts =====
${renderStepFunctionsContract(flussFunctions)}
${renderEndTypes(flussFunctions)}

// ===== Section: Runner =====
${renderRunner(flussFunctions)}

/**
 * ${FlussTSStateJSONStart}${entireStateJSON}${FlussTSStateJSONEnd}
 */
`
