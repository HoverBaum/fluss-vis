import { END_NODE_ID, START_NODE_ID } from '@/stores/nodeHelpers'
import { FlussArgument, FlussFunction } from './useExport'
import { FlussTSStateJSONEnd, FlussTSStateJSONStart } from '@/lib/constants'

// String.raw helper for clean template sections
const ts = String.raw

// Input for generating a complete, typed runner file for the current flow
type FlussTemplateParams = {
  customTypes: string
  flussFunctions: FlussFunction[]
  flussInputs: FlussArgument[]
  entireStateJSON: string
}

// ---------- Small helpers to render sections ----------

const renderBanner = () => ts`/**
 * Auto-generated by flussTemplate.
 * Sections below are assembled from the current flow graph to produce a typed runner.
 */`

const renderCustomTypes = (customTypes: string) => ts`
// Custom type definitions from the editor
${customTypes}`

const renderFlussInputs = (inputs: FlussArgument[]) => ts`
export type FlussInputs = {
  ${inputs.map((arg) => `${arg.identifier}: ${arg.type}`).join(';\n  ')}
}`

const renderStepFunctionTypes = (flussFunctions: FlussFunction[]) =>
  flussFunctions
    .map(
      (fn) => ts`
export type ${fn.functionTypeIdentifier} = (args: {
  ${fn.arguments.map((arg) => `${arg.name}: ${arg.type}`).join(';\n  ')}
}) => Promise<${fn.returnType}> | ${fn.returnType}
`
    )
    .join('\n')

const renderStepIO = (functions: FlussFunction[]) => ts`
type StepIO = {
  ${START_NODE_ID}: {
    input: FlussInputs
    output: FlussInputs
  }${functions
    .map(
      (fn) => ts`
  ${fn.functionName}: {
    input: Parameters<${fn.functionTypeIdentifier}>[0]
    output: ReturnType<${fn.functionTypeIdentifier}>
  }`
    )
    .join('')}
}`

const renderRuntimeCore = () => ts`
type FlussRunStatus = 'waiting' | 'running' | 'done' | 'error'

// Step IDs derive directly from StepIO keys
type FlussStepId = keyof StepIO

// Mapping of step id to executable function (excludes start/end)
type StepFunctions = {
  [K in Exclude<FlussStepId, '${START_NODE_ID}' | '${END_NODE_ID}'>]: (
    args: StepIO[K]['input']
  ) => Promise<StepIO[K]['output']> | StepIO[K]['output']
}

// A single step instance within the running flow
type Step<ID extends FlussStepId> = {
  id: ID
  status: FlussRunStatus
  execute: (
    args: StepIO[ID]['input']
  ) => Promise<StepIO[ID]['output']> | StepIO[ID]['output']
  arguments: Array<{
    sourceStepId: FlussStepId
    argumentName: keyof StepIO[ID]['input']
    sourceProperty?: string
  }>
  result?: StepIO[ID]['output']
  error?: Error
}

// Entire runtime state keyed by step id
type FlowState = {
  [K in FlussStepId]: Step<K>
}

function canStepRun<ID extends FlussStepId>(step: Step<ID>, flowState: FlowState): boolean {
  return step.arguments.every((arg) => flowState[arg.sourceStepId].status === 'done')
}

async function executeStep<ID extends FlussStepId>(step: Step<ID>, flowState: FlowState) {
  try {
    const input = {} as StepIO[ID]['input']

    // Build inputs from declared argument wiring
    for (const arg of step.arguments) {
      const sourceStep = flowState[arg.sourceStepId]
      if (sourceStep.status !== 'done') {
        throw new Error('Source step ' + arg.sourceStepId + ' not complete for ' + String(arg.argumentName))
      }
      if (arg.sourceProperty === undefined || sourceStep.result === undefined) {
        input[arg.argumentName as keyof StepIO[ID]['input']] =
          sourceStep.result as StepIO[ID]['input'][keyof StepIO[ID]['input']]
      } else {
        input[arg.argumentName as keyof StepIO[ID]['input']] =
          sourceStep.result[arg.sourceProperty as keyof typeof sourceStep.result]
      }
    }

  // Log the exact input used to start this step
  console.log('Executing', String(step.id), 'with input:', input)

    const result = await step.execute(input)
  // Log the output produced by this step
  console.log('Result for', String(step.id), ':', result)
    step.status = 'done'
    step.result = result
  } catch (err) {
    step.status = 'error'
    step.error = err instanceof Error ? err : new Error(String(err))
    throw step.error
  }
}
`

const renderFlowStateInit = (flussFunctions: FlussFunction[]) => ts`{
  ${START_NODE_ID}: {
    id: '${START_NODE_ID}',
    status: 'done',
    execute: (args) => args,
    arguments: [],
    result: inputs,
  },
  ${flussFunctions
    .map(
      (fn) => ts`${fn.functionName}: {
    id: '${fn.functionName}',
    status: 'waiting',
    execute: ${fn.stepId === END_NODE_ID ? '(args) => args' : `stepFunctions.${fn.functionName}`},
    arguments: [
      ${fn.arguments
        .map(
          (arg) => ts`{
        sourceStepId: '${arg.source}',
        argumentName: '${arg.name}',
        ${arg.usesEntireOutput ? '' : `sourceProperty: '${arg.name}'`}
      }`
        )
        .join(',\n')}
    ]
  }`
    )
    .join(',\n')}
}`

const renderRunner = (flussFunctions: FlussFunction[]) => ts`
export async function runFluss(params: {
  inputs: FlussInputs
  stepFunctions: StepFunctions
}): Promise<StepIO['${END_NODE_ID}']['output']> {
  const { inputs, stepFunctions } = params

  // Initialize all steps for this flow instance
  const flowState: FlowState = ${renderFlowStateInit(flussFunctions)}

  // Event-driven iterative scheduler: start steps as soon as they become runnable
  const running = new Map<FlussStepId, Promise<void>>()

  const tryStartRunnable = () => {
    // Find all steps that can be started right now
    const runnableNow: FlussStepId[] = []
    for (const step of Object.values(flowState) as Array<Step<FlussStepId>>) {
      if (step.status !== 'waiting') continue
      if (running.has(step.id)) continue
      if (!canStepRun(step, flowState)) continue
      runnableNow.push(step.id)
    }

    if (runnableNow.length > 0) {
      console.log('Runnable now:', runnableNow)
    }

    // Start them immediately
    let started = 0
    for (const id of runnableNow) {
      const step = flowState[id] as Step<FlussStepId>
      console.log('Starting step:', step.id)
      step.status = 'running'
      const p = executeStep(step, flowState).finally(() => {
        running.delete(step.id)
        console.log('Finished step:', step.id)
      })
      running.set(step.id, p)
      started++
    }

    if (running.size > 0) {
      console.log('Currently running:', Array.from(running.keys()))
    }

    return started
  }

  // Kick off any steps that are immediately runnable
  tryStartRunnable()

  while (true) {
    // If all done, return end result
    const allDone = Object.values(flowState).every((s) => s.status === 'done')
    if (allDone) {
      if (!flowState.${END_NODE_ID}.result) throw new Error('End step has no result')
      return flowState.${END_NODE_ID}.result
    }

    // If we can start new work right away, do it and loop without waiting
    if (tryStartRunnable() > 0) continue

    // Nothing to start right now. If nothing is running, we are stuck.
    if (running.size === 0) {
      throw new Error('No steps can be run and not all steps are done')
    }

    // Wait until one running step completes, then loop to start newly-unblocked ones immediately
    await Promise.race(running.values())
  }
}
`

export const flussTemplate = ({
  customTypes,
  flussFunctions,
  flussInputs,
  entireStateJSON,
}: FlussTemplateParams) => ts`
${renderBanner()}

// ===== Section: Custom Types =====
${renderCustomTypes(customTypes)}

// ===== Section: Flow Inputs =====
${renderFlussInputs(flussInputs)}

// ===== Section: Step Function Signatures (from node definitions) =====
${renderStepFunctionTypes(flussFunctions)}

// ===== Section: StepIO (wires inputs/outputs per step) =====
${renderStepIO(flussFunctions)}

// ===== Section: Runtime Types and Engine =====
${renderRuntimeCore()}

// ===== Section: Runner =====
${renderRunner(flussFunctions)}

/**
 * ${FlussTSStateJSONStart}${entireStateJSON}${FlussTSStateJSONEnd}
 */
`
